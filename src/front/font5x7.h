#define FONT_NGLYPHS ((int)(sizeof font_src / sizeof font_src[0]))

typedef struct { uint32_t cp; uint8_t rows[FONT_H]; } FontGlyph;
static FontGlyph font_glyphs[sizeof font_src / sizeof font_src[0]];
static int font_ready;

static void font_init(void)
{
    if (font_ready) return;
    for (int i = 0; i < FONT_NGLYPHS; i++) {
        font_glyphs[i].cp = font_src[i].cp;
        for (int r = 0; r < FONT_H; r++) {
            const char *s = font_src[i].r[r];
            uint8_t bits = 0;
            for (int c = 0; c < FONT_W && s[c]; c++)
                if (s[c] == '#') bits |= (uint8_t)(0x10 >> c);
            font_glyphs[i].rows[r] = bits;
        }
    }
    font_ready = 1;
}

static inline const FontGlyph *font_glyph(uint32_t cp)
{
    if (!font_ready) font_init();
    if (cp == 0xA0 || cp == 0x202F) cp = ' ';
    for (int i = 0; i < FONT_NGLYPHS; i++)
        if (font_glyphs[i].cp == cp) return &font_glyphs[i];
    /* unknown: accented letters fall back to the plain letter, others to '?' */
    if (cp >= 0xC0 && cp <= 0xC5) return font_glyph('A');
    if (cp >= 0xE0 && cp <= 0xE5) return font_glyph('a');
    if (cp >= 0xC8 && cp <= 0xCB) return font_glyph('E');
    if (cp >= 0xCC && cp <= 0xCF) return font_glyph('I');
    if (cp >= 0xD2 && cp <= 0xD6) return font_glyph('O');
    if (cp >= 0xD9 && cp <= 0xDC) return font_glyph('U');
    if (cp == 0x2018 || cp == 0x2032) return font_glyph('\'');
    if (cp == 0x201C || cp == 0x201D) return font_glyph('"');
    if (cp == 0x2013 || cp == 0x2014) return font_glyph('-');
    if (cp != '?') return font_glyph('?');
    return &font_glyphs[0];
}

/* decode one UTF-8 code point; advances *s */
static uint32_t utf8_next(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t c = p[0];
    int n = 1;
    if (c >= 0xF0 && p[1] && p[2] && p[3]) { c = ((c & 7u) << 18) | ((p[1] & 63u) << 12) | ((p[2] & 63u) << 6) | (p[3] & 63u); n = 4; }
    else if (c >= 0xE0 && p[1] && p[2]) { c = ((c & 15u) << 12) | ((p[1] & 63u) << 6) | (p[2] & 63u); n = 3; }
    else if (c >= 0xC0 && p[1]) { c = ((c & 31u) << 6) | (p[1] & 63u); n = 2; }
    *s += n;
    return c;
}

/* number of code points of a UTF-8 string (= its width in cells) */
static inline int utf8_len(const char *s)
{
    int n = 0;
    while (*s) { utf8_next(&s); n++; }
    return n;
}

